import assert from "node:assert/strict";
import {randomUUID} from "node:crypto";
import {chromium,expect} from "@playwright/test";
import {createClient} from "@supabase/supabase-js";
import {localStack,check} from "./local.mjs";

const {url,key,admin}=localStack();
const school=randomUUID(),email="entregas-"+school+"@example.test",password=randomUUID();
const actor=createClient(url,key,{auth:{persistSession:false,autoRefreshToken:false}});
const browser=await chromium.launch({channel:process.platform==="win32"?"msedge":undefined});
const page=await browser.newPage({viewport:{width:1150,height:800}});
page.setDefaultTimeout(15000);
const go=name=>page.getByRole("link",{name,exact:true}).first().click();
const click=name=>page.getByRole("button",{name,exact:true}).click();
const fill=(name,value)=>page.getByLabel(name,{exact:true}).fill(value);
const open=name=>page.locator("summary").filter({hasText:new RegExp("^"+name+"$")}).click();
const rpc=(op,d,token=randomUUID())=>actor.rpc("material_command",{sid:school,op,d,token});
const run=async(op,d,token)=>check(await rpc(op,d,token));
const list=async table=>check(await actor.from(table).select("*").eq("school_id",school));
let user;
try {
  user=check(await admin.auth.admin.createUser({email,password,email_confirm:true})).user.id;
  check(await admin.from("schools").insert({id:school,name:"Teste de entregas"}));
  check(await actor.auth.signInWithPassword({email,password}));
  assert.ok((await rpc("teacher",{name:"Sem vínculo"})).error);
  check(await admin.from("school_memberships").insert({school_id:school,user_id:user}));
  const year=await run("year",{year:2026});
  const turma=await run("class",{year,name:"7º A"}),subject=await run("subject",{name:"Matemática"});
  const ids=[];
  for(let i=0;i<10;i++) ids.push(await run("teacher",{name:"Docente "+i}));
  const fields={title:"Planos",period:"1º bimestre",type:"Plano de aula",year,date:"2026-01-10",ids,class:turma,subject};
  assert.ok((await rpc("request",{...fields,ids:[ids[0],randomUUID()]})).error);
  assert.equal((await list("material_requests")).length,0);
  const token=randomUUID();
  const req=await run("request",fields,token);
  assert.equal(await run("request",fields,token),req);
  let rows=await list("delivery_summary"); assert.equal(rows.length,10);
  const ob=rows.find(x=>x.teacher_id===ids[0]),second=rows.find(x=>x.teacher_id===ids[1]);
  assert.ok((await rpc("approve",{id:ob.id,revision:1})).error);
  assert.ok((await rpc("receive",{id:ob.id,revision:1,channel:"papel",received:"2099-01-11T10:00"})).error);
  await run("assign",{teacher:ids[0],year,class:turma,subject});
  await run("teacher_active",{id:ids[0],active:false});
  assert.equal((await list("delivery_summary")).length,10);
  await run("exempt",{id:second.id,revision:1,reason:"Licença"});
  assert.equal((await list("delivery_summary")).filter(d=>d.state==="dispensado").length,1);
  await run("reactivate",{id:second.id,revision:2});
  await page.goto("http://127.0.0.1:3000");await fill("E-mail",email);await fill("Senha",password);await click("Entrar");
  await go("Professores");await open("Cadastrar professor");await fill("Nome do professor","Docente adicional");await click("Salvar professor");
  await expect(page.locator("summary",{hasText:"Docente adicional · Ativo"})).toBeVisible();
  await go("Entregas");await go("Nova solicitação");
  await fill("Título do material","Avaliações");await fill("Tipo de material","Prova");await fill("Período de referência","2º bimestre");
  await page.getByLabel("Ano letivo",{exact:true}).selectOption(year);await fill("Data do prazo","2026-04-15");
  await page.getByRole("checkbox",{name:"Docente adicional"}).check();await click("Criar solicitação");
  await expect(page.getByRole("heading",{name:"Avaliações",exact:true})).toBeVisible();
  await go("Entregas");await go("Planos");
  await open("Adicionar professores");await page.getByRole("checkbox",{name:"Docente adicional"}).check();await click("Adicionar selecionados");
  await expect(page.getByRole("link",{name:"Docente adicional · Planos"})).toBeVisible();
  await go("Docente 0 · Planos");await fill("Data real da entrega","2026-01-11T09:00");await fill("Observações","Primeira via");
  await click("Salvar recebimento");await expect(page.getByText("Versão 1 · Aguardando conferência",{exact:true})).toBeVisible();
  await open("Alterar prazo individual");await fill("Data do prazo","2026-02-10");await fill("Justificativa","Reposição");await click("Alterar prazo deste professor");
  await expect(page.getByText(/10\/01\/2026 → 10\/02\/2026/)).toBeVisible();
  await expect(page.getByText("Primeira entrega atrasada",{exact:true})).toBeVisible();
  await open("Anexar arquivo à versão 1");
  const input=page.getByLabel("Arquivo (até 10 MiB)");
  await input.setInputFiles({name:"plano.pdf",mimeType:"application/pdf",buffer:Buffer.from("arquivo incorreto")});await click("Enviar arquivo");
  await expect(page.getByText("O conteúdo do arquivo não corresponde à extensão.")).toBeVisible();
  const pdf=Buffer.from("%PDF-1.4 arquivo escolar de teste");
  await input.setInputFiles({name:"plano.pdf",mimeType:"application/pdf",buffer:pdf});await click("Enviar arquivo");
  const download=page.getByRole("link",{name:"Baixar plano.pdf"});await expect(download).toBeVisible();
  const path=await download.getAttribute("href");
  const downloaded=await page.request.get(new URL(path,page.url()).href);
  assert.equal(downloaded.status(),200); assert.deepEqual(await downloaded.body(),pdf);
  assert.equal((await fetch(new URL(path,page.url()))).status,404);
  await open("Solicitar ajustes");await fill("Orientação","Revisar objetivos");await fill("Prazo de correção","2026-02-15");await click("Enviar orientação de ajuste");
  await expect(page.getByText("Versão 1 · Precisa de ajustes",{exact:true})).toBeVisible();
  await fill("Data real da entrega","2026-02-12T10:30");await click("Salvar recebimento");await expect(page.getByText("Versão 2 · Aguardando conferência",{exact:true})).toBeVisible();
  await click("Marcar como conferido");await expect(page.getByText("Versão 2 · Conferido",{exact:true})).toBeVisible();
  await page.reload();await expect(download).toBeVisible();
  rows=await list("delivery_summary");assert.equal(rows.filter(r=>r.state==="recebido").length,1);
  const done=rows.find(r=>r.id===ob.id);assert.equal(done.review,"aprovado");assert.equal(done.first_late,true);
  await run("deadline",{id:req,ids:[second.id],date:"2026-03-01",collective:"on",reason:"Mudança coletiva"});
  rows=await list("delivery_summary");assert.equal(rows.find(r=>r.id===second.id).due_date,"2026-03-01");assert.equal(rows.find(r=>r.id===ob.id).due_date,"2026-02-10");
  await go("Agenda");await fill("Ir para a data","2026-03-01");await go("Entrega · Docente 1 · Planos");await expect(page.getByRole("heading",{name:"Docente 1",exact:true})).toBeVisible();
  await page.setViewportSize({width:390,height:820});assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
  console.log("Coleta para dez professores, prazos, dispensa, versões, conferência, agenda e download privado aprovados.");
} finally {
  await browser.close();
  const files=check(await admin.from("attachments").select("object_path").eq("school_id",school));
  if(files.length) check(await admin.storage.from("materiais").remove(files.map(f=>f.object_path)));
  for(const table of ["attachments","receipt_versions","delivery_obligations","material_requests","teaching_assignments","teachers","classes","subjects","academic_years","audit_events","school_memberships"])
    check(await admin.from(table).delete().eq("school_id",school));
  check(await admin.from("schools").delete().eq("id",school));
  if(user) check(await admin.auth.admin.deleteUser(user));
}
